def sha(path):
    with Path(path).open('rb') as stream:return hashlib.file_digest(stream,'sha256').hexdigest()


def write(path,value):path.write_text(json.dumps(value,indent=2)+'\n')


def generated():
    # Restore the exact authored generator, without checking out a closed
    # candidate or treating its retired binary as a current qualification.
    prior=json.loads(gen.git('show',ORIGIN_PLAN+':'+str((gen.A/'qsa-page4-current.json').relative_to(P))))
    raw=gen.git('show',ORIGIN+':'+GENERATOR)
    guards.require(hashlib.sha256(raw).hexdigest()==prior['input_sha256'][GENERATOR],
        'original generator identity changed')
    module=types.ModuleType('original_main_authored_page4_generator')
    exec(compile(raw,ORIGIN+':'+GENERATOR,'exec'),module.__dict__)
    bodies=module.generated(P)
    result={name:bodies[name] for name in ('control.cpp','page4.cpp','qsa-page4-variants.hpp','timing.cpp')}
    for name,body in result.items():
        original_path=str(B/'qsa-page4-address-v2'/name)
        guards.require(hashlib.sha256(body).hexdigest()==prior['generated'][original_path],
            'reconstructed original generated bytes changed: '+name)
    return result


def inputs(revision):
    names=set((*NATIVE,'tests/sycl/qsa_bf16_prefix.cpp','tests/sycl/qsa_bf16_prefix_layout_bench.cpp',
        'tools/sycl/measurement_environment.json'))
    names.update(gen.git('ls-files','include').decode().splitlines())
    pending=[Path(__file__).resolve()];seen=set()
    while pending:
        path=pending.pop()
        if path in seen:continue
        seen.add(path);names.add(str(path.relative_to(P)))
        for node in ast.walk(ast.parse(path.read_text())):
            mods=[v.name for v in node.names] if isinstance(node,ast.Import) else [node.module] if isinstance(node,ast.ImportFrom) else []
            for module in mods:
                local=path.parent/((module or '').split('.')[0]+'.py')
                if local.is_file():pending.append(local)
    pins={}
    for name in sorted(names):
        raw=gen.git('show',revision+':'+name)
        guards.require(raw==(P/name).read_bytes(),'commit exact codegen input: '+name)
        pins[name]=hashlib.sha256(raw).hexdigest()
    for name in NATIVE:
        guards.require(gen.git('show',ORIGIN+':'+name)==(P/name).read_bytes(),'native origin changed')
    return pins


def runtime(plan):
    settings=gen.committed(P/'tools/sycl/measurement_environment.json')
    for name,item in settings['runtime_elfs'].items():
        delta=qualified.DELTA.get(name)
        if delta:guards.require(delta[0]==item['sha256'],'runtime baseline changed')
        guards.require(sha(name)==(delta[1] if delta else item['sha256']),'runtime changed: '+name)
    reference=gen.committed(qualified.COMPONENT)
    guards.require(reference['passed'] and reference['complete'] and reference['ownership_closed']
        and not reference['active'] and reference['fresh_faults']==[],'qualified runtime component required')
    expected={name:dict(qualified_sha256=pair[0],candidate_sha256=pair[1]) for name,pair in qualified.DELTA.items()}
    guards.require({name:{key:item[key] for key in ('qualified_sha256','candidate_sha256')}
        for name,item in reference['runtime_asset_delta'].items()}==expected,'runtime qualification delta changed')
    guards.require(validation.preload_qualification()==plan['validation_preload'],'validation preload changed')


def admission(record):
    guards.require(inputs(record['source_commit'])==record['inputs'],'codegen source/recipe changed')
    full,proof,_=resource.qualification()
    guards.require(full['binary']==record['retained_engine'] and proof==record['native_qualification'],
        'selected engine qualification changed')
    for name,body in generated().items():
        path=ROOT/name
        guards.require(path.read_bytes()==body and sha(path)==record['generated'][str(path)],'generated source changed')
    manifest=record['compiler_inputs'];guards.require(sha(manifest['path'])==manifest['sha256'],'SDK manifest changed')
    rows=json.loads(Path(manifest['path']).read_text());guards.require(len(rows)==manifest['files'],'SDK inventory changed')
    for row in rows:guards.require(sha(row['path'])==row['sha256'],'compiler/dependency changed: '+row['path'])
    if 'binary' in record:guards.require(sha(record['binary']['path'])==record['binary']['sha256'],'fixture changed')


