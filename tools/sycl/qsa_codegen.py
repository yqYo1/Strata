def build():
    record=gen.committed(RESULT)
    guards.require(record['stage']=='prepared' and record==json.loads((ROOT/'build-plan.json').read_text())
        and not (ROOT/'build-record.json').exists(),'fresh committed build required; inspect owner')
    admission(record);owner=None
    def persist():
        record['active']=bool(owner and owner.active is not None)
        write(ROOT/'build-record.json',dict(record,owned_commands=owner.commands if owner else []))
    owner=supervision.Owner(ROOT/'build-owned',persist)
    record.update(stage='building',ownership_closed=False);persist()
    try:
        for i,command in enumerate(record['commands']):
            print(f'Compiling/linking codegen fixture {i+1}/9',flush=True)
            entry,_,_=owner.run('build-'+str(i),command,record['build_environment'],P,wall=420,cpu=900,
                rss_cap=12<<30,text_cap=8<<20,file_cap=512<<20,total_cap=1<<30)
            guards.require(supervision.closed(entry) and entry['exit_code']==0,'codegen build did not close normally')
        admission(record)
        record.update(stage='built',passed=True,complete=True,binary=dict(path=str(ROOT/'fixture'),
            sha256=sha(ROOT/'fixture'),bytes=(ROOT/'fixture').stat().st_size))
    except BaseException as error:record.update(stage='failed',passed=False,complete=False,error=repr(error))
    finally:
        record['ownership_closed']=owner.active is None and all(supervision.closed(c) for c in owner.commands)
        persist();write(RESULT,record)
    print(json.dumps({k:record.get(k) for k in ('stage','passed','ownership_closed','error')}),flush=True)
    return 0 if record['passed'] else 1


