def fixture_evidence(stdout):
    samples=[]
    for line in stdout.splitlines():
        if not line.startswith('sample '):continue
        pairs=[word.split('=',1) for word in line.split()[1:]]
        guards.require(all(len(p)==2 for p in pairs) and len({p[0] for p in pairs})==len(pairs),'malformed/duplicate sample keys')
        row=dict(pairs);order=int(row['order']);round_=int(row['round']);arm=int(row['variant'])
        guards.require(int(row['process'])==0 and row['cells']=='97' and row['queries']=='3'
            and row['cap']=='33' and row['page_size']=='4' and row['pattern']=='gather'
            and arm==(round_+order)%3 and row['implementation']==('default','control','page4')[arm]
            and row['compared']==str(3*24*256) and all(row[k]=='PASS' for k in ('route','exact_bits','guards','status')),
            'incorrect native small fixture coverage')
        samples.append((round_,order))
    guards.require(sorted(samples)==[(r,o) for r in range(6) for o in range(3)]
        and stdout.splitlines().count('page4_timing_routes fast=7 generic=0')==1
        and stdout.splitlines().count('case cells=97 queries=3 cap=33 pattern=gather samples=18 full_bits=PASS guards=PASS inputs=PASS status=PASS')==1
        and stdout.count('fixture_status=PASS ')==1,'incomplete native exact-bit/route fixture')
    return dict(samples=18,compared_per_sample=18432,fast_routes=7,generic_routes=0,exact_bits_guards_inputs=True)


def capture_evidence(stdout,stderr,root):
    table=tables.device_summary(stderr);properties=[];calls={}
    template='prefix_batch_impl<33, false, false, true, true, true, true, false>'
    arm=lambda name:2 if '::page4::' in name else 1 if '::control::' in name else 0
    selected=lambda name:template in name and '[SIMD16 ' in name and '{128; 1; 1}]' in name
    for row in table['rows']:
        if selected(row['name']):
            key=arm(row['name']);guards.require(key not in calls,'ambiguous compute family');calls[key]=row['calls']
    for line in stderr.split('=== Kernel Properties ===')[1].splitlines():
        parts=[p.strip() for p in line.rsplit(',',7)]
        if len(parts)!=8 or not selected(parts[0]):continue
        key=arm(parts[0]);simd,nargs,slm,private,spill,grf=map(int,parts[2:])
        guards.require(parts[1]=='JIT' and simd==16 and grf==128 and slm==32 and private==0
            and nargs==(17 if key==2 else 18) and spill==(22208 if key==2 else 12480),
            'reconstruction does not reproduce prior Page4 resource identity')
        properties.append(dict(arm=key,SIMD=simd,arguments=nargs,raw_SLM=slm,private=private,spill=spill,GRF=grf))
    guards.require(calls=={0:8,1:7,2:7} and sorted(p['arm'] for p in properties)==[0,1,2],'compute coverage mismatch')
    metadata=emitted_resources(stdout,stderr)
    launched=[m for m in metadata if m['observed_launches'] and m['execution_env'].get('simd_size')=='16']
    guards.require(len(launched)==3 and sorted(m['observed_launches']['launches'] for m in launched)==[7,7,8],
        'three traced executed compute metadata blocks required')
    files=[p for p in (root/'isa').rglob('*') if p.is_file()]
    guards.require(not any(p.is_symlink() for p in files),'unexpected dump link')
    matched=[]
    for item in launched:
        name=item['kernel'];images=[]
        for path in files:
            if path.suffix!='.asm':continue
            with path.open(errors='replace') as stream:header=stream.read(6000)
            if name in header:images.append(path)
        guards.require(len(images)==1,'one unambiguous executed GenISA image required per compute kernel')
        matched.append(dict(kernel=name,execution_env=item['execution_env'],
            per_thread_memory_buffers=item['per_thread_memory_buffers'],observed_launches=item['observed_launches'],
            asm=dict(path=str(images[0]),sha256=sha(images[0]),bytes=images[0].stat().st_size)))
    guards.require(not list((root/'trace').rglob('*.json')),'unexpected profiler timeline')
    return dict(properties=properties,compute_calls=calls,conserved_device_ns=table['total_device_ns'],
        executed=matched,dump_files=len(files),dump_bytes=sum(p.stat().st_size for p in files),
        files=[dict(path=str(p),sha256=sha(p),bytes=p.stat().st_size) for p in sorted(files)],
        limits='Static executed-image attribution only; observers alter timings. Spill allocation/static sends do not establish dynamic traffic/occupancy, critical path, clean speed or causal attribution.')


def run(mode):
    record=gen.committed(RESULT);plan=record['check_plan'];root=ROOT/mode
    guards.require(plan['mode']==mode and plan==json.loads((root/'plan.json').read_text())
        and not (root/'record.json').exists() and record['stage']=='built' and record['passed']
        and record['complete'] and record['ownership_closed'] and not record['active'],
        'matching fresh committed check required; inspect owner')
    admission(record);runtime(plan)
    if mode=='capture':
        assets=aggregate.profile_assets(gen.committed(aggregate.RESULT))
        guards.require(plan['collector_assets']=={k:assets[k] for k in ('collector','launcher','preload')},'collector assets changed')
    boot=Path('/proc/sys/kernel/random/boot_id').read_text().strip()
    journal=subprocess.check_output(['journalctl','-k','-b','-n','0','--show-cursor','--no-pager'],text=True,timeout=15)
    cursor=next(line.split(': ',1)[1] for line in journal.splitlines() if line.startswith('-- cursor: '))
    result=dict(mode=mode,source_commit=record['source_commit'],binary=record['binary'],passed=False,complete=False,
        active=False,ownership_closed=False);owner=None;entry=None
    def persist():
        result['active']=bool(owner and owner.active is not None)
        write(root/'record.json',dict(result,owned_commands=owner.commands if owner else []))
    owner=supervision.Owner(root/'owned',persist);persist()
    session=Path('/dev/shm/uctrl'+str(os.getuid())+'_'+plan['session']) if plan['session'] else None
    try:
        guards.require(session is None or not session.exists(),'unique session already exists')
        print('Executing bounded codegen '+mode,flush=True);b=plan['budgets']
        entry,out,err=owner.run(mode,plan['command'],plan['environment'],P,wall=b['wall_s'],cpu=b['cpu_s'],
            rss_cap=b['rss_bytes'],text_cap=b['text_bytes'],file_cap=b['file_bytes'],total_cap=b['total_bytes'])
        stdout,stderr=out.read_text(),err.read_text()
        guards.require(supervision.closed(entry) and entry['exit_code']==0,'native diagnostic did not close normally')
        result['validation']=validation.preload_evidence(stderr,entry['pid'])
        guards.require(result['validation']['loader']==plan['validation_preload']['loader']['path'],'loader identity changed')
        body=stderr.split(f'strata UR validation: pid={entry["pid"]} phase=before-main',1)[1]
        guards.require(not re.search(r'UR_RESULT_ERROR_|ZE_RESULT_ERROR_|terminate called|cleanup failed|strata UR validation failure:',body),
            'runtime/validation diagnostic failed')
        result.update(fixture=fixture_evidence(stdout),stdout_sha256=sha(out),stderr_sha256=sha(err))
        if mode=='capture':result['capture']=capture_evidence(stdout,stderr,root)
        result.update(passed=True,complete=True)
    except BaseException as error:result['error']=repr(error)
    finally:
        if session is not None and entry is not None and supervision.closed(entry) and owner.active is None:
            if session.exists():
                stop,_,_=owner.run('stop',[plan['collector_assets']['launcher']['path'],'--stop',plan['session']],
                    plan['environment'],P,wall=15,cpu=15,rss_cap=2<<30,text_cap=1<<20,file_cap=32<<20,total_cap=192<<20)
                guards.require(supervision.closed(stop) and stop['exit_code']==0,'collector stop failed')
            guards.require(not session.exists(),'collector session remains')
        result['ownership_closed']=owner.active is None and all(supervision.closed(c) for c in owner.commands)
        postchecks(result,boot,cursor);persist()
        record.setdefault('checks',[]).append(result);record['GPU_executed']=True;write(RESULT,record)
    print(json.dumps({k:result.get(k) for k in ('mode','passed','complete','ownership_closed','fresh_faults','error')}),flush=True)
    return 0 if result['passed'] else 1


